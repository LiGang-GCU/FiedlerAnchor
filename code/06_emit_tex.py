def scrub_apostrophes(indir):
    """LaTeX needs no escaping for an apostrophe, but several caption strings
    above were authored with a stray backslash before it.  Normalise once, at
    the point the files are written, rather than inside each literal."""
    T = os.path.join(indir, 'tables')
    for fn in os.listdir(T):
        p = os.path.join(T, fn)
        s = open(p, encoding='utf-8').read()
        s2 = s.replace(chr(92) + "'", "'")
        if s2 != s:
            open(p, 'w', encoding='utf-8').write(s2)
            print('scrubbed apostrophes in', fn)


